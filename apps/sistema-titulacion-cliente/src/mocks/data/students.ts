// Funciones auxiliares para los mocks
export const findStudentById = (id: string): Student | undefined => {
  return mockStudents.find((student) => student.id === id);
};

export const findStudentByControlNumber = (
  controlNumber: string
): Student | undefined => {
  return mockStudents.find(
    (student) => student.controlNumber === controlNumber
  );
};

export const generateStudentId = (): string => {
  const studentMaxId = Math.max(
    ...mockStudents.map((s) => parseInt(s.id, 10)),
    0
  );
  const capturedFieldsMaxId = Math.max(
    ...mockCapturedFields.map((fields) => parseInt(fields.studentId, 10)),
    0
  );
  const maxId = Math.max(studentMaxId, capturedFieldsMaxId);
  return String(maxId + 1);
};

export const generateControlNumber = (year: number): string => {
  const existingNumbers = mockStudents
    .filter((s) => s.controlNumber.startsWith(year.toString()))
    .map((s) => parseInt(s.controlNumber.substring(4)));
  const maxNumber =
    existingNumbers.length > 0 ? Math.max(...existingNumbers) : 0;
  return `${year}${(maxNumber + 1).toString().padStart(4, '0')}`;
};
